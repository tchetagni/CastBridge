"""Automatic quality control of a question bank (docs/QUIZ.md, section Contrôle qualité).

Errors make a question unusable (it is kept out of the packs and listed); warnings are reported for the human reviewer.
Bank-level checks: exact and near duplicates, answer-position balance, difficulty and region split, template share.
"""
import re
from collections import Counter, defaultdict

from .core import COURSES, NEEDED, PER_GAME, norm, sha

MAX_TEXT, MAX_CHOICE = 260, 100
MAX_TEMPLATE_SHARE = 0.08          # one template must not be more than 8 % of a course
MAX_COMPUTED_SHARE = 0.80          # a course must not be more than 80 % generated by calculation
COMMON_MISSPELLINGS = {            # cheap spelling net for the names that matter most here
    "yaounde": "Yaoundé", "yaoundée": "Yaoundé", "doula": "Douala", "camerone": "Cameroun",
    "bafousam": "Bafoussam", "ngaoundere": "Ngaoundéré", "sénégale": "Sénégal",
    "egypte": "Égypte", "ethiopie": "Éthiopie", "tchade": "Tchad", "gabonn": "Gabon", 
}
BAD_CHOICE_START = ("toutes ces", "aucune de", "les deux", "tous les", "a et b", "b et c")
WORD = re.compile(r"[^\W_]+", re.U)


def proper(text):
    """Capitalized words other than the first (names of places, people...): the subject of a factual question."""
    return {w for w in re.findall(r"[A-ZÀ-Ý][\w'’-]+", text)[1:]}


def masked(text):
    t = text.lower().replace("\u00a0", " ")
    return re.sub(r"\s+", " ", re.sub(r"\d+(?:[., ]\d+)*", "#", t)).strip()


def check_question(q):
    """Returns (errors, warnings) for one question dict."""
    e, w = [], []
    for k in ("id", "track", "region", "category", "question", "choices", "answer", "explanation", "source", "status", "verif"):
        if q.get(k) in (None, "", []):
            e.append("champ manquant : " + k)
    if e:
        return e, w
    t, ch = q["question"], q["choices"]
    if not isinstance(ch, list) or len(ch) != 4:
        return ["il faut 4 choix"], w
    if not isinstance(q["answer"], int) or not 0 <= q["answer"] < 4:
        e.append("index de réponse invalide")
    if not isinstance(q.get("difficulty"), int) or not 1 <= q["difficulty"] <= 5:
        e.append("difficulté hors 1..5")
    if q["region"] not in ("CM", "AF", "WORLD"):
        e.append("région inconnue")
    if q["status"] not in ("review", "approved"):
        e.append("statut inconnu")
    if q["verif"] not in ("computed", "fact", "import"):
        e.append("verif inconnu")
    if len({norm(c) for c in ch}) != 4:
        e.append("choix identiques ou presque")
    if any(not c.strip() for c in ch):
        e.append("choix vide")
    if not t.rstrip().endswith("?"):
        e.append("la question doit finir par ?")
    if len(t) > MAX_TEXT:
        e.append("question trop longue (%d)" % len(t))
    if any(len(c) > MAX_CHOICE for c in ch):
        e.append("choix trop long")
    if any(c.lower().startswith(BAD_CHOICE_START) for c in ch):
        e.append("choix qui dépend de l'ordre (« toutes ces réponses »…)")
    for s in (t, *ch, q["explanation"]):
        if s != s.strip() or "  " in s or re.search(r"\s[,.](?!\w)", s):
            e.append("espaces mal placés : %r" % s[:40]); break
    if not (t[0].isupper() or t[0].isdigit() or t[0] in "«(√∫−-"):
        w.append("la question ne commence pas par une majuscule")
    for s in (t, *ch):
        if s.count("(") != s.count(")") or s.count("«") != s.count("»"):
            e.append("parenthèses ou guillemets non fermés")
            break
    low = " ".join([t] + ch).lower() + " "
    for bad, good in COMMON_MISSPELLINGS.items():
        if bad in low.replace(good.lower(), ""):
            w.append("orthographe ? « %s » → « %s »" % (bad.strip(), good))
    if re.search(r"\b(\w{2,})\s+\1\b", t.lower()) and not re.search(r"\b(\d+|nous nous|vous vous|tu tu)\b", t.lower()):
        w.append("mot répété")
    if len(q["explanation"]) < 8:
        e.append("explication trop courte")
    if q["verif"] == "computed" and not q.get("tpl"):
        e.append("question calculée sans modèle (tpl)")
    return e, w


def check_bank(questions):
    """Bank-level checks. Returns dict(errors={id: [..]}, warnings={id: [..]}, bank=[..problems..], dropped=set(ids))."""
    errors, warnings, bank = defaultdict(list), defaultdict(list), []
    for q in questions:
        e, w = check_question(q)
        if e:
            errors[q["id"]] += e
        if w:
            warnings[q["id"]] += w
    # duplicates: same id, same normalized text in a course
    ids, texts = {}, {}
    for q in questions:
        if q["id"] in ids:
            errors[q["id"]].append("id en double avec une autre question")
        ids[q["id"]] = q
        key = (q["track"], q["level"], q["field"], norm(q["question"]))
        if key in texts and texts[key] != q["id"]:
            errors[q["id"]].append("même question que " + texts[key])
        texts.setdefault(key, q["id"])
    # near duplicates: same masked wording from two different templates; or same answer + similar words (non computed)
    by_mask = defaultdict(set)
    for q in questions:
        if q["verif"] != "computed":                 # generated questions share their wording on purpose: only the numbers change
            by_mask[(q["track"], q["level"], q["field"], masked(q["question"]))].add(q.get("tpl") or q["id"])
    mask_clash = {k for k, v in by_mask.items() if len(v) > 1}
    for q in questions:
        if q["verif"] != "computed" and (q["track"], q["level"], q["field"], masked(q["question"])) in mask_clash:
            warnings[q["id"]].append("formulation identique à celle d'un autre modèle (chiffres masqués)")
    facts = [q for q in questions if q["verif"] != "computed"]
    by_right = defaultdict(list)
    for q in facts:
        by_right[(q["track"], q["level"], q["field"], norm(q["choices"][q["answer"]]))].append(q)
    for group in by_right.values():
        if len(group) < 2:
            continue
        toks = [(q, set(WORD.findall(norm(q["question"])))) for q in group]
        for i in range(len(toks)):
            for j in range(i + 1, len(toks)):
                a, b = toks[i][1], toks[j][1]
                if toks[i][0].get("tpl") and toks[i][0].get("tpl") == toks[j][0].get("tpl"):
                    continue                  # same template, different subject: expected
                pa, pb = proper(toks[i][0]["question"]), proper(toks[j][0]["question"])
                if (pa or pb) and pa != pb:
                    continue                  # same wording but about two different named things
                if a and b and len(a & b) / len(a | b) >= 0.6:
                    warnings[toks[j][0]["id"]].append("quasi-doublon de " + toks[i][0]["id"] + " (même réponse, mots proches)")
    # the four-choice sets of two questions identical (same 4 answers and same right one) are suspicious for facts
    # per course balance
    for course, c in COURSES.items():
        qs = [q for q in questions if (q["track"], q["level"], q["field"]) == (c["track"], c["level"], c["field"]) and q["id"] not in errors]
        if not qs:
            continue
        pos = Counter(q["answer"] for q in qs)
        for p in range(4):
            share = pos[p] / len(qs)
            if abs(share - 0.25) > 0.05:
                bank.append("%s : la bonne réponse est en position %s dans %.0f %% des questions (attendu ~25 %%)" % (course, "ABCD"[p], 100 * share))
        tpl = Counter(q.get("tpl") for q in qs if q["verif"] == "computed")
        for t, n in tpl.items():
            if n / len(qs) > MAX_TEMPLATE_SHARE and len(qs) > 500:
                bank.append("%s : le modèle « %s » fait %.0f %% de la banque (max %.0f %%)" % (course, t, 100 * n / len(qs), 100 * MAX_TEMPLATE_SHARE))
        comp = sum(1 for q in qs if q["verif"] == "computed") / len(qs)
        if comp > MAX_COMPUTED_SHARE and len(qs) > 500:
            bank.append("%s : %.0f %% des questions sont générées par calcul (max %.0f %%)" % (course, 100 * comp, 100 * MAX_COMPUTED_SHARE))
        longest = sum(1 for q in facts if (q["track"], q["level"], q["field"]) == (c["track"], c["level"], c["field"])
                      and len(q["choices"][q["answer"]]) > max(len(x) for i, x in enumerate(q["choices"]) if i != q["answer"]))
        nf = sum(1 for q in facts if (q["track"], q["level"], q["field"]) == (c["track"], c["level"], c["field"]))
        if nf > 200 and longest / nf > 0.45:
            bank.append("%s : la bonne réponse est la plus longue dans %.0f %% des questions factuelles" % (course, 100 * longest / nf))
    return dict(errors=dict(errors), warnings=dict(warnings), bank=bank, dropped=set(errors))


def games(qs, general):
    """How many games of PER_GAME questions the list gives without repeat (same rule as QuizBank.remainingFresh)."""
    if general:
        by = Counter(q["region"] for q in qs)
        return int(min(by["CM"] / (0.7 * PER_GAME), by["AF"] / (0.2 * PER_GAME), by["WORLD"] / (0.1 * PER_GAME)))
    return len(qs) // PER_GAME


def coverage(questions):
    """Per-course coverage numbers for the report / catalog."""
    out = {}
    for course, c in COURSES.items():
        qs = [q for q in questions if (q["track"], q["level"], q["field"]) == (c["track"], c["level"], c["field"])]
        general = c["track"] == "general"
        by_d = Counter(q["difficulty"] for q in qs)
        out[course] = dict(
            label=c["label"], total=len(qs),
            approved=sum(1 for q in qs if q["status"] == "approved"),
            review=sum(1 for q in qs if q["status"] != "approved"),
            computed=sum(1 for q in qs if q["verif"] == "computed"),
            fact=sum(1 for q in qs if q["verif"] == "fact"),
            imported=sum(1 for q in qs if q["verif"] == "import"),
            by_region=dict(Counter(q["region"] for q in qs)),
            by_difficulty={d: by_d.get(d, 0) for d in range(1, 6)},
            by_category=dict(Counter(q["category"] for q in qs).most_common()),
            templates=len({q.get("tpl") for q in qs if q["verif"] == "computed"}),
            games=games(qs, general),
            games_by_difficulty=min((by_d.get(d, 0) // 3 for d in range(1, 6)), default=0),
            answer_positions={"ABCD"[p]: sum(1 for q in qs if q["answer"] == p) for p in range(4)},
        )
        if general:
            by = Counter(q["region"] for q in qs)
            out[course]["missing"] = dict(CM=max(0, int(0.7 * NEEDED) - by["CM"]), AF=max(0, int(0.2 * NEEDED) - by["AF"]),
                                          WORLD=max(0, int(0.1 * NEEDED) - by["WORLD"]))
        else:
            out[course]["missing_total"] = max(0, NEEDED - len(qs))
    return out
