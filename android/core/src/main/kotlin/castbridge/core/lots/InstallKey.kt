package castbridge.core.lots

import castbridge.core.crypto.SecretWrapper
import castbridge.core.lots.InstallKeyPolicy.KeyState
import castbridge.core.owner.SafeFile
import castbridge.core.owner.X25519
import java.io.File
import java.nio.file.Files
import java.nio.file.StandardCopyOption
import java.security.MessageDigest
import java.security.SecureRandom

/**
 * The X25519 key pair of ONE installation of CastBridge-TV (docs/coordination/DESIGN-W4-ENVELOPPE-LOCATIONS.md § 3). The private part never leaves the TV and never enters a token;
 * the public part travels in the device request (`install=x25519|<hex>`) and rental keys are boxed for it. [priv] is the 32-byte seed (the clamp is applied by [X25519]).
 */
class InstallKey(val priv: ByteArray, val pub: ByteArray) {
    init { require(priv.size == 32 && pub.size == 32) }

    /** 16 hex = the first 8 bytes of SHA-256(pub): for logs, no personal data. */
    val installId: String get() = MessageDigest.getInstance("SHA-256").digest(pub).take(8).joinToString("") { "%02x".format(it) }

    companion object {
        fun fromSeed(seed: ByteArray) = InstallKey(seed.copyOf(), X25519.publicKey(seed))
        fun generate(random: SecureRandom = SecureRandom()) = fromSeed(ByteArray(32).also(random::nextBytes))
    }
}

/** The key cannot be read or created FOR NOW (Keystore unavailable, disk error). No file was touched: the caller retries later (backoff, forever). */
class InstallKeyUnavailableException(message: String, cause: Throwable? = null) : IllegalStateException(message, cause)

/** The key file exists but is lost for good (wrong tag, invalidated or confirmed-absent Keystore key, damaged file). Stays so until an explicit [InstallKeyStore.reset]. */
class InstallKeyUnreadableException(message: String) : IllegalStateException(message)

/**
 * `<dir>/install.key` (+ `.bak`), written by [SafeFile]:
 * ```
 * castbridge-install-key-v1
 * pub=<64 hex>
 * wrap=<label of the wrapper>
 * priv=<hex of the wrapped blob>
 * createdAt=<ms>
 * ```
 * LIFECYCLE (audits w4-03, simplified): an existing key file is NEVER overwritten, moved or regenerated by [loadOrCreate].
 *  - FIRST creation only (no `install.key` and no `.bak`): a key is generated and wrapped by [creator]; if the wrapper fails nothing is written (no plain key, ever: `PlainWrapper` is for tests)
 *    and [InstallKeyUnavailableException] is thrown (nothing v2 exists yet, so nothing is lost by waiting).
 *  - Existing key: read with the wrapper its `wrap=` label names ([readers]). A wrapper answering null (lost for good) or a damaged file => [KeyState.UNREADABLE] (sticky until [reset]); a wrapper
 *    that throws => [KeyState.UNAVAILABLE] (transient, retry with backoff). The main file is read first, then the `.bak`.
 *  - [reset] (explicit owner decision) renames the current files to `.reset-<ms>` (never deleted) and installs a fresh key.
 */
class InstallKeyStore(
    private val dir: File, private val creator: SecretWrapper, private val random: SecureRandom = SecureRandom(), private val now: () -> Long = System::currentTimeMillis,
    /** The wrapper able to read a blob stored under a label (null = foreign envelope: unreadable here). */
    private val readers: (String) -> SecretWrapper? = { label -> creator.takeIf { it.label == label } },
) {
    private val file = File(dir, FILE)
    private val bak = SafeFile.bak(file)

    @Volatile var state: KeyState = KeyState.PENDING; private set
    /** What happened at the last first creation / read from the backup (a French sentence for the journal), null otherwise. */
    @Volatile var loadNote: String? = null; private set
    private var cached: InstallKey? = null

    /** No key file at all (neither main nor `.bak`)? Throws [InstallKeyUnavailableException] when the folder cannot be listed (never "absent" on a mere I/O error). */
    fun isAbsent(): Boolean = names().let { FILE !in it && bak.name !in it }

    private fun names(): Set<String> {
        if (!dir.exists()) return emptySet()
        return dir.list()?.toSet() ?: throw InstallKeyUnavailableException("dossier de la clé d'installation illisible")
    }

    @Synchronized fun loadOrCreate(): InstallKey {
        cached?.let { return it }
        if (state == KeyState.UNREADABLE) throw InstallKeyUnreadableException(InstallKeyPolicy.UNREADABLE_MESSAGE)
        try {
            val present = names()
            if (FILE !in present && bak.name !in present) return create()
            var transient: Throwable? = null
            for (f in listOf(file, bak)) {
                if (f.name !in present) continue
                val k = try { read(f) } catch (e: Exception) { transient = e; break } ?: continue      // a main file that fails FOR NOW is not replaced by an older .bak
                if (f == bak) loadNote = "clé d'installation relue depuis la copie de sécurité"
                return ready(k)
            }
            if (transient == null) { state = KeyState.UNREADABLE; throw InstallKeyUnreadableException(InstallKeyPolicy.UNREADABLE_MESSAGE) }
            throw InstallKeyUnavailableException("clé d'installation momentanément illisible (coffre de clés indisponible) : conservée telle quelle, nouvel essai plus tard", transient)
        } catch (e: InstallKeyUnreadableException) { throw e
        } catch (e: Exception) { state = KeyState.UNAVAILABLE; throw if (e is InstallKeyUnavailableException) e else InstallKeyUnavailableException("clé d'installation indisponible", e) }
    }

    private fun ready(k: InstallKey): InstallKey { cached = k; state = KeyState.READY; return k }

    /** First creation: nothing is written unless the wrapper works AND reads its own blob back. */
    private fun create(): InstallKey {
        val fresh = InstallKey.generate(random)
        val text = render(fresh, creator)
        SafeFile.write(file, text) { parse(it) != null }
        runCatching { Files.copy(file.toPath(), bak.toPath(), StandardCopyOption.REPLACE_EXISTING) }       // best effort: a cut before it leaves the main file alone, which is fine
        loadNote = "nouvelle clé d'installation générée"
        return ready(fresh)
    }

    /** Reads one key file with the wrapper ITS label names. Null = lost for good here; THROWS when the wrapper failed (transient). */
    private fun read(f: File): InstallKey? {
        val p = parse(f.readText()) ?: return null
        val seed = (readers(p.wrap) ?: return null).unwrap(p.blob) ?: return null
        return seed.takeIf { it.size == 32 }?.let { InstallKey.fromSeed(it) }?.takeIf { it.pub.contentEquals(p.pub) }
    }

    /**
     * EXPLICIT owner reset: a fresh key replaces the current one, whatever its state; the old files are renamed, never deleted. Order (a readable key is always in the folder, whatever the
     * power cut): the fresh key is written under a temporary name and read back FIRST (a failing wrapper changes nothing); then main -> `.reset-<ms>`; staged -> main; old `.bak` ->
     * `.bak.reset-<ms>`; copy of main -> `.bak`. [step] is called after each step (tests cut the power there). Returns [InstallKeyPolicy.RESET_NOTE].
     */
    @Synchronized fun reset(step: (Int) -> Unit = {}): String {
        val stamp = now(); val staged = File(dir, "$FILE.reset-new")
        val fresh = InstallKey.generate(random)
        try {
            val text = render(fresh, creator); dir.mkdirs()
            java.io.FileOutputStream(staged).use { it.write(text.toByteArray()); it.fd.sync() }
        } catch (e: Exception) { throw InstallKeyUnavailableException("coffre de clés indisponible : clé d'installation inchangée", e) }
        step(1)
        if (file.isFile && !bak.isFile) Files.copy(file.toPath(), bak.toPath())                          // so that a cut after the next step still leaves a readable key
        step(2)
        val old = aside(file, stamp); step(3)
        try { Files.move(staged.toPath(), file.toPath(), StandardCopyOption.ATOMIC_MOVE) } catch (e: Exception) { old?.let { runCatching { Files.move(it.toPath(), file.toPath()) } }; throw e }   // put the old file back
        step(4)
        aside(bak, stamp); step(5)
        runCatching { Files.copy(file.toPath(), bak.toPath(), StandardCopyOption.REPLACE_EXISTING) }
        loadNote = "clé d'installation réinitialisée"; ready(fresh)
        return InstallKeyPolicy.RESET_NOTE
    }

    /** Renames [f] to `<name>.reset-<stamp>` (a free name: never over a kept file). Returns the new name (null if [f] is absent), throws on failure. */
    private fun aside(f: File, stamp: Long): File? {
        if (!f.isFile) return null
        var target = File(dir, "${f.name}.reset-$stamp"); var i = 1
        while (target.exists()) target = File(dir, "${f.name}.reset-$stamp-${i++}")
        Files.move(f.toPath(), target.toPath()); return target
    }

    private class Parsed(val pub: ByteArray, val wrap: String, val blob: ByteArray)

    private fun hex(b: ByteArray) = b.joinToString("") { "%02x".format(it) }
    private fun unhex(s: String): ByteArray? = if (s.length % 2 == 0 && s.all { it in '0'..'9' || it in 'a'..'f' }) s.chunked(2).map { it.toInt(16).toByte() }.toByteArray() else null

    /** The file text of [k] under [w]; the wrapper must read its own blob back (a wrapper that does not is a failing wrapper: nothing is written). */
    private fun render(k: InstallKey, w: SecretWrapper): String {
        val blob = w.wrap(k.priv)
        check(w.unwrap(blob)?.contentEquals(k.priv) == true) { "aller-retour de l'enveloppe incohérent" }
        return listOf(HEADER, "pub=${hex(k.pub)}", "wrap=${w.label}", "priv=${hex(blob)}", "createdAt=${now()}").joinToString("\n") + "\n"
    }

    private fun parse(text: String): Parsed? {
        val lines = text.replace("\r", "").lines().map { it.trim() }.filter { it.isNotEmpty() }
        if (lines.firstOrNull() != HEADER) return null
        val kv = lines.drop(1).mapNotNull { l -> l.indexOf('=').takeIf { it > 0 }?.let { l.substring(0, it) to l.substring(it + 1) } }.toMap()
        val pub = kv["pub"]?.let(::unhex)?.takeIf { it.size == 32 } ?: return null
        val blob = kv["priv"]?.let(::unhex)?.takeIf { it.isNotEmpty() } ?: return null
        return Parsed(pub, kv["wrap"].orEmpty(), blob)
    }

    companion object { const val FILE = "install.key"; private const val HEADER = "castbridge-install-key-v1" }
}
